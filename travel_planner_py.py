class WeatherSystem:
    def __init__(self, seed=42):
        random.seed(seed)
        self._m: dict[tuple,str] = {}

    def set_weather(self, a, b, cond):
        if cond not in WEATHER_CONDITIONS:
            raise ValueError(f"Unknown: {cond}")
        self._m[tuple(sorted([a,b]))] = cond

    def get_weather(self, a, b) -> str:
        k = tuple(sorted([a,b]))
        if k not in self._m:
            self._m[k] = random.choice(WEATHER_CONDITIONS)
        return self._m[k]

    def get_mult(self, a, b) -> float:
        return WEATHER_MULT[self.get_weather(a,b)]


