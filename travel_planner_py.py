class RoadblockSystem:
    def __init__(self):
        self._bl: set[tuple]  = set()
        self._rs: dict[tuple,str] = {}

    def add(self, a, b, reason="Under maintenance"):
        k = tuple(sorted([a,b]))
        self._bl.add(k); self._rs[k] = reason

    def remove(self, a, b):
        k = tuple(sorted([a,b]))
        self._bl.discard(k); self._rs.pop(k, None)

    def blocked(self, a, b) -> bool:
        return tuple(sorted([a,b])) in self._bl

    def reason(self, a, b) -> str:
        return self._rs.get(tuple(sorted([a,b])), "Unknown")

    def all(self) -> list[tuple]:
        return list(self._bl)


