class Stack:
    """Array-backed Stack — O(1) push / pop."""
    def __init__(self):            self._d = []
    def push(self, x):             self._d.append(x)
    def pop(self):
        if self.is_empty(): raise IndexError("Stack underflow")
        return self._d.pop()
    def peek(self):
        if self.is_empty(): raise IndexError("Stack empty")
        return self._d[-1]
    def is_empty(self):            return not self._d
    def size(self):                return len(self._d)
    def __repr__(self):            return f"Stack({self._d})"


# ════════════════════════════════════════════════════════════════
#  QUEUE
# ════════════════════════════════════════════════════════════════
class Queue:
    """Deque-backed Queue — O(1) enqueue / dequeue."""
    def __init__(self):            self._d = deque()
    def enqueue(self, x):          self._d.append(x)
    def dequeue(self):
        if self.is_empty(): raise IndexError("Queue underflow")
        return self._d.popleft()
    def front(self):               return self._d[0]
    def is_empty(self):            return not self._d
    def size(self):                return len(self._d)
    def __repr__(self):            return f"Queue({list(self._d)})"


