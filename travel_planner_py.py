#  PRIORITY QUEUE  (min-heap — Dijkstra)
# ════════════════════════════════════════════════════════════════
class PriorityQueue:
    def __init__(self):            self._h = []
    def push(self, pri, item):     heapq.heappush(self._h, (pri, item))
    def pop(self):                 return heapq.heappop(self._h)
    def is_empty(self):            return not self._h


