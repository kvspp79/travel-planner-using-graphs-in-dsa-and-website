class TravelGraph:
    """
    Weighted undirected graph (Adjacency List).
    Edge: (neighbor, distance_km, cost_inr, time_hr)
    """
    def __init__(self):
        self.adj: dict[str, list] = defaultdict(list)
        self.cities: set[str] = set()
        self.weather   = WeatherSystem()
        self.roadblocks = RoadblockSystem()
        self.history   = Stack()          # route history

    # ── Construction ────────────────────────
    def add_route(self, a, b, dist, cost, time):
        for c in (a, b): self.cities.add(c)
        self.adj[a].append((b, dist, cost, time))
        self.adj[b].append((a, dist, cost, time))

    def get_all_edges(self):
        seen, edges = set(), []
        for city, nbrs in self.adj.items():
            for nb, *_ in nbrs:
                k = tuple(sorted([city, nb]))
                if k not in seen:
                    seen.add(k); edges.append(k)
        return edges

    # ── Dijkstra ────────────────────────────
    def dijkstra(self, src, tgt, weight="distance", weather=False):
        widx = {"distance":0,"cost":1,"time":2}[weight]
        dist = {c: math.inf for c in self.cities}
        prev = {c: None    for c in self.cities}
        dist[src] = 0
        pq = PriorityQueue(); pq.push(0, src)

        while not pq.is_empty():
            d, u = pq.pop()
            if d > dist[u]: continue
            for nb, *ws in self.adj[u]:
                if self.roadblocks.blocked(u, nb): continue
                w = ws[widx]
                if weather: w *= self.weather.get_mult(u, nb)
                alt = dist[u] + w
                if alt < dist[nb]:
                    dist[nb] = alt; prev[nb] = u
                    pq.push(alt, nb)

        path, node = [], tgt
        while node: path.append(node); node = prev[node]
        path.reverse()
        if not path or path[0] != src: return math.inf, []
        return dist[tgt], path

    # ── BFS ─────────────────────────────────
    def bfs(self, src) -> list:
        visited, order = {src}, []
        q = Queue(); q.enqueue(src)
        while not q.is_empty():
            c = q.dequeue(); order.append(c)
            for nb, *_ in sorted(self.adj[c], key=lambda x: x[0]):
                if nb not in visited and not self.roadblocks.blocked(c, nb):
                    visited.add(nb); q.enqueue(nb)
        return order

    # ── DFS ─────────────────────────────────
    def dfs(self, src, visited=None) -> list:
        if visited is None: visited = set()
        visited.add(src); order = [src]
        for nb, *_ in sorted(self.adj[src], key=lambda x: x[0]):
            if nb not in visited and not self.roadblocks.blocked(src, nb):
                order.extend(self.dfs(nb, visited))
        return order

    # ── All Paths ───────────────────────────
    def all_paths(self, src, tgt, path=None) -> list:
        if path is None: path = [src]
        if src == tgt: return [path[:]]
        res = []
        for nb, *_ in self.adj[src]:
            if nb not in path and not self.roadblocks.blocked(src, nb):
                path.append(nb)
                res.extend(self.all_paths(nb, tgt, path))
                path.pop()
        return res

    # ── Nearest City ─────────────────────────
    def nearest_cities(self, src: str, n: int = 3) -> list:
        """Return n nearest cities by distance from src."""
        results = []
        for tgt in self.cities:
            if tgt == src: continue
            total, path = self.dijkstra(src, tgt, "distance")
            if path: results.append((total, tgt))
        results.sort()
        return results[:n]

    # ── Multi-stop route ─────────────────────
    def multi_stop_route(self, waypoints: list[str], weight="distance"):
        """Chain Dijkstra across multiple waypoints."""
        full_path, grand_total = [], 0.0
        for i in range(len(waypoints) - 1):
            total, path = self.dijkstra(waypoints[i], waypoints[i+1], weight)
            if not path:
                return math.inf, []
            grand_total += total
            full_path.extend(path if i == 0 else path[1:])
        return grand_total, full_path

    # ── History helpers ──────────────────────
    def push_history(self, entry): self.history.push(entry)
    def undo_last(self):
        if self.history.is_empty():
            print("  Nothing to undo."); return None
        return self.history.pop()


