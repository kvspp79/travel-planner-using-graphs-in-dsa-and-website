def pick_city(prompt, cities) -> str | None:
    raw = input(prompt).strip()
    for c in cities:
        if c.lower() == raw.lower(): return c
    if raw.isdigit():
        idx = int(raw)-1
        if 0 <= idx < len(cities): return cities[idx]
    print(f"  '{raw}' not found.")
    return None

def pick_vehicle() -> str:
    print("\n  Select vehicle type:")
    opts = list(FUEL_RATES.keys())
    for i,v in enumerate(opts,1): print(f"    {i}. {v}")
